"""Pydantic validation schemas for the AI Project Magnet feature.
"""

from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field, field_validator


class SkillLevel(str, Enum):
    BEGINNER = "beginner"
    INTERMEDIATE = "intermediate"
    ADVANCED = "advanced"


ALLOWED_DOMAINS = [
    "Computer Vision",
    "Natural Language Processing",
    "Generative AI & LLMs",
    "Web & Fullstack AI",
    "Healthcare AI",
    "FinTech & Algorithmic Trading",
    "IoT & Embedded AI",
    "Data Analytics & Business Intelligence",
    "EdTech & Smart Learning",
    "Cybersecurity AI",
]


class MagnetRequest(BaseModel):
    """Student profile input for personalized project recommendation."""
    interests: List[str] = Field(
        ...,
        min_length=1,
        max_length=5,
        description="1 to 5 interest areas (e.g. Computer Vision, Generative AI)"
    )
    skill_level: SkillLevel = Field(
        ...,
        description="Current engineering skill level: beginner, intermediate, or advanced"
    )
    technologies_known: List[str] = Field(
        ...,
        min_length=1,
        max_length=8,
        description="1 to 8 programming languages or frameworks known"
    )
    career_goal: str = Field(
        ...,
        min_length=5,
        max_length=300,
        description="Learning goal or career aspiration (e.g., crack campus placements)"
    )

    @field_validator("interests", "technologies_known")
    @classmethod
    def clean_and_validate_lists(cls, values: List[str]) -> List[str]:
        cleaned = [item.strip() for item in values if item and item.strip()]
        if not cleaned:
            raise ValueError("List must contain at least one non-empty item")
        for item in cleaned:
            if len(item) > 50:
                raise ValueError(f"Tag item '{item[:20]}...' exceeds maximum length of 50 characters")
        return cleaned

    @field_validator("career_goal")
    @classmethod
    def clean_career_goal(cls, value: str) -> str:
        cleaned = value.strip()
        if len(cleaned) < 5:
            raise ValueError("Career goal must be at least 5 characters long")
        return cleaned


class ProjectRecommendation(BaseModel):
    """Structured AI Project Recommendation generated by Gemini or Fallback."""
    project_title: str = Field(
        ...,
        min_length=5,
        max_length=120,
        description="Engaging, resume-ready project title"
    )
    problem_statement: str = Field(
        ...,
        min_length=20,
        max_length=500,
        description="Real-world problem or use case this project addresses"
    )
    project_description: str = Field(
        ...,
        min_length=30,
        max_length=1000,
        description="Clear architectural description of what the student will build"
    )
    fit_explanation: str = Field(
        ...,
        min_length=20,
        max_length=500,
        description="Why this specific project fits their stated interests, tech stack, and goals"
    )
    recommended_tech_stack: List[str] = Field(
        ...,
        min_length=1,
        max_length=10,
        description="Libraries and tools needed (e.g. Python, FastAPI, Hugging Face)"
    )
    difficulty_level: str = Field(
        ...,
        min_length=3,
        max_length=50,
        description="Target difficulty (e.g., Beginner-Friendly, Intermediate)"
    )
    estimated_scope: str = Field(
        ...,
        min_length=10,
        max_length=300,
        description="Realistic scope for a beginner attending 'Build Your First AI Project in 60 Minutes'"
    )
    first_three_steps: List[str] = Field(
        ...,
        min_length=3,
        max_length=3,
        description="Exactly 3 sequential, beginner-friendly implementation steps"
    )
    workshop_learning_outcome: str = Field(
        ...,
        min_length=15,
        max_length=400,
        description="Tangible takeaway the student achieves by completing the 60-minute workshop"
    )


class MagnetMetadata(BaseModel):
    """Telemetry and audit metadata for the recommendation response."""
    is_fallback: bool
    provider: str
    model: str
    latency_ms: int
    cached: bool = False
    status: str = "success"
    note: Optional[str] = None


class MagnetResponse(BaseModel):
    """Complete response envelope for /api/v1/magnet/recommend."""
    recommendation: ProjectRecommendation
    metadata: MagnetMetadata
